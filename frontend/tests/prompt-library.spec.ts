import { test, expect } from './setup'

test('访客可浏览、搜索、滑动并复制提示词，再返回原首页', async ({ page }, info) => {
  await page.route('**/api/auth/me', route => route.fulfill({ status: 401, json: { error: { code: 'AUTH_REQUIRED' } } }))
  await page.route('**/api/prompt-images/**', route => route.fulfill({ path: 'tests/fixtures/sample-image.png', contentType: 'image/png' }))
  await page.route('**/api/prompts?**', route => {
    const query = new URL(route.request().url()).searchParams.get('q')
    return route.fulfill({ json: { prompts: query === '不存在' ? [] : [{ id: 'one', title: '雨夜街景', content: '雨夜霓虹，电影感光影', images: [{ id: 'a', url: '/api/prompt-images/a' }, { id: 'b', url: '/api/prompt-images/b' }, { id: 'c', url: '/api/prompt-images/c' }], createdAt: '2026-11-01T00:00:00Z', updatedAt: '2026-11-01T00:00:00Z' }], hasMore: false } })
  })
  await page.addInitScript(() => { Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (value: string) => { (window as unknown as { copied: string }).copied = value } } }) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '我的画布' })).toBeVisible()
  await page.getByRole('link', { name: '提示词', exact: true }).click()
  await expect(page).toHaveURL(/view=prompts/)
  await expect(page.getByRole('heading', { name: '提示词', exact: true })).toBeVisible()
  await expect(page.getByText('雨夜街景')).toBeVisible()
  await expect(page.getByText('无需登录即可浏览')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /添加提示词|新增提示词/ })).toHaveCount(0)
  await page.getByRole('button', { name: '下一张图片' }).click()
  await expect(page.getByText('2 / 3')).toBeVisible()
  await page.getByRole('button', { name: '查看雨夜街景第 2 张大图' }).click()
  await expect(page.getByRole('dialog', { name: '雨夜街景大图' })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: '下一张' }).click()
  await expect(page.getByRole('dialog').getByText('3 / 3')).toBeVisible()
  await page.getByRole('button', { name: '关闭大图' }).click()
  await page.getByRole('button', { name: '复制提示词' }).click()
  await expect(page.getByText('已复制')).toBeVisible()
  expect(await page.evaluate(() => (window as unknown as { copied: string }).copied)).toBe('雨夜霓虹，电影感光影')
  await page.screenshot({ path: info.outputPath('prompt-library-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: '提示词', exact: true })).toBeVisible()
  expect(await page.locator('.public-shell').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('prompt-library-mobile.png') })
  await page.getByLabel('搜索提示词').fill('不存在')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.getByText('没有找到匹配的提示词。')).toBeVisible()
  await page.getByRole('link', { name: '首页', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的画布' })).toBeVisible()
})
